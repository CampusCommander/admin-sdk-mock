import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const DOCUMENTS = [
  'directory_v1',
  'chromemanagement_v1',
  'drive_v3',
  'sheets_v4',
];
const root = new URL('../', import.meta.url);

interface Schema {
  properties?: Record<string, Schema>;
  items?: Schema;
  additionalProperties?: Schema;
}

interface Discovery {
  revision: string;
  schemas: Record<string, Schema>;
}

function read(name: string): Discovery {
  return JSON.parse(
    readFileSync(new URL(`test/contract/discovery/${name}.json`, root), 'utf8'),
  ) as Discovery;
}

function walk(schema: Schema | undefined, names: Set<string>): void {
  if (!schema || typeof schema !== 'object') return;
  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    names.add(name);
    walk(property, names);
  }
  walk(schema.items, names);
  walk(schema.additionalProperties, names);
}

/** Every property name declared anywhere in the four discovery documents. */
export function collectSchemaNames(): { names: string[]; revisions: string[] } {
  const names = new Set<string>();
  const revisions: string[] = [];
  for (const document of DOCUMENTS) {
    const discovery = read(document);
    revisions.push(`${document} ${discovery.revision}`);
    for (const schema of Object.values(discovery.schemas)) walk(schema, names);
  }
  return { names: [...names].sort(), revisions };
}

export function render(): string {
  const { names, revisions } = collectSchemaNames();
  const listed = `${revisions.slice(0, -1).join(', ')}, and ${revisions.at(-1)}`;
  return `// Generated by scripts/schema-names.ts from the discovery documents ${listed}.
// Run \`node scripts/schema-names.ts\` and \`npm run format\` to regenerate.

/** Every property name that the Directory, Chrome Management, Drive, and Sheets schemas declare. */
export const SCHEMA_NAMES: ReadonlySet<string> = new Set([
${names.map((name) => `  '${name}',`).join('\n')}
]);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  writeFileSync(new URL('src/store/schema-names.ts', root), render());
