import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

/** The documents of milestones 1 to 3. Their names form the first block. */
const CORE = ['directory_v1', 'chromemanagement_v1'];
/** The documents of the Drive slice. Their new names form the second block. */
const ADDED = ['drive_v3', 'sheets_v4'];
const DOCUMENTS = [...CORE, ...ADDED];
const root = new URL('../', import.meta.url);

interface Schema {
  properties?: Record<string, Schema>;
  items?: Schema;
  additionalProperties?: Schema;
}

interface Discovery {
  revision: string;
  schemas: Record<string, Schema>;
}

function read(name: string): Discovery {
  return JSON.parse(
    readFileSync(new URL(`test/contract/discovery/${name}.json`, root), 'utf8'),
  ) as Discovery;
}

function walk(schema: Schema | undefined, names: Set<string>): void {
  if (!schema || typeof schema !== 'object') return;
  for (const [name, property] of Object.entries(schema.properties ?? {})) {
    names.add(name);
    walk(property, names);
  }
  walk(schema.items, names);
  walk(schema.additionalProperties, names);
}

function namesOf(documents: readonly string[]): Set<string> {
  const names = new Set<string>();
  for (const document of documents)
    for (const schema of Object.values(read(document).schemas))
      walk(schema, names);
  return names;
}

/**
 * Every property name declared anywhere in the four discovery documents, in two blocks:
 * the names that the milestone 1 to 3 documents declare, then the names that the Drive and
 * Sheets documents add. A name in both blocks appears in the first one alone.
 */
export function collectSchemaNames(): {
  names: string[];
  added: string[];
  revisions: string[];
} {
  const core = namesOf(CORE);
  const added = namesOf(ADDED);
  return {
    names: [...core].sort(),
    added: [...added].filter((name) => !core.has(name)).sort(),
    revisions: DOCUMENTS.map(
      (document) => `${document} ${read(document).revision}`,
    ),
  };
}

export function render(): string {
  const { names, added, revisions } = collectSchemaNames();
  const listed = `${revisions.slice(0, -1).join(', ')}, and ${revisions.at(-1)}`;
  return `// Generated by scripts/schema-names.ts from the discovery documents ${listed}.
// Run \`node scripts/schema-names.ts\` and \`npm run format\` to regenerate.

/**
 * Every property name that the Directory and Chrome Management schemas declare, then the
 * names that the Drive and Sheets schemas add. A name in both blocks appears once.
 */
export const SCHEMA_NAMES: ReadonlySet<string> = new Set([
${names.map((name) => `  '${name}',`).join('\n')}
  // The Drive v3 and Sheets v4 documents.
${added.map((name) => `  '${name}',`).join('\n')}
]);
`;
}

if (process.argv[1] === fileURLToPath(import.meta.url))
  writeFileSync(new URL('src/store/schema-names.ts', root), render());
