export interface ModelInfo {
  name: string;
  manufacturer: 'Lenovo' | 'Acer' | 'Dell' | 'HP' | 'ASUS' | 'Samsung' | 'CTL';
  /** Automatic updates until, as YYYY-MM. */
  aue: string;
  ramGb: number;
  storageGb: number;
  /** Battery design capacity in mAh. */
  designCapacity: number;
  cpu: string;
  board: string;
  weight: number;
}

